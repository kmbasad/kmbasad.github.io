n = collections.Counter()
for r in rows:
    if r[0] in OWN: r[1] = OWN[r[0]]; n['his rewrite'] += 1
    for pat, rep in SUBS:
        r[1], k = re.subn(pat, rep, r[1]); n[rep] += k
    for a, b in EDITS.get(r[0], []):
        assert r[1].count(a) == 1, (r[0], a)
        r[1] = r[1].replace(a, b); n['edit'] += 1
open('candide-dhaka.tsv', 'w', encoding='utf-8').write(''.join(f'{a}\t{b}\n' for a, b in rows))
print(dict(n))
