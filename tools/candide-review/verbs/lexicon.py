from morph import consonant, aa, vowel, table

def lower(B):
    for a, b in [('ি', 'ে'), ('ু', 'ো'), ('উ', 'ও'), ('ই', 'এ')]:
        i = B.find(a)
        if i >= 0: return B[:i] + b + B[i + 1:]
    return B
def mutate(B):
    i = B.rfind('া')
    if i >= 0: return B[:i] + 'ে' + B[i + 1:]
    if B.startswith('আ'): return 'এ' + B[1:]
    return B

